/** word (uppercase) -> clue, for O(1) lookup while filling a grid. */
export const CROSSWORD_CLUES: Record<string, string> = (() => {
  const map: Record<string, string> = {};
  for (const entry of CROSSWORD_BANK) {
    if (!map[entry.word]) map[entry.word] = entry.clue;
  }
  return map;
})();

/** Bank words grouped by length: { 3: [...], 4: [...], 5: [...] }. */
export const CROSSWORD_WORDS_BY_LENGTH: Record<number, string[]> = (() => {
  const byLength: Record<number, string[]> = {};
  for (const entry of CROSSWORD_BANK) {
    if (!byLength[entry.word.length]) byLength[entry.word.length] = [];
    if (!byLength[entry.word.length].includes(entry.word)) {
      byLength[entry.word.length].push(entry.word);
    }
  }
  return byLength;
})();
